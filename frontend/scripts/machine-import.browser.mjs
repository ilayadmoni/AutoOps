import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mockMachineImport } from './machine-import.fixtures.mjs';
import { verifyFolderBrowser } from './machine-folder.browser-checks.mjs';
import { verifyFolderSelection } from './machine-folder-selection.browser-checks.mjs';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1366, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.addInitScript(() => localStorage.setItem('autoops.lang', 'en'));
const state = await mockMachineImport(page);

try {
  await page.goto(`${process.env.UI_TEST_URL ?? 'http://localhost:5173'}/machines`);
  await page.locator('.fab').click();
  await page.getByRole('menuitem', { name: 'Add machine', exact: true }).waitFor();
  await page.getByRole('menuitem', { name: 'Import MobaXterm sessions', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Import MobaXterm sessions', exact: true });
  await dialog.locator('input[type=file]').setInputFiles({ name: 'test.mxtsessions', mimeType: 'text/plain', buffer: Buffer.from('[Bookmarks]\nSubRep=Lab') });
  await dialog.getByText('2 of 4 sessions selected', { exact: true }).waitFor();
  assert.equal(await dialog.locator('details[open]').count(), 0, 'all preview folders start collapsed');
  await dialog.getByRole('checkbox', { name: 'Select all eligible sessions', exact: true }).uncheck();
  await dialog.getByText('0 of 4 sessions selected', { exact: true }).waitFor();
  await dialog.getByRole('checkbox', { name: 'Select all eligible sessions', exact: true }).check();
  assert.equal(await dialog.locator('details[open]').count(), 0, 'select all preserves collapsed folders');
  await verifyFolderSelection(page, dialog);
  assert.equal(await dialog.getByRole('checkbox', { name: 'App node', exact: true }).count(), 0);
  const lab = dialog.locator('details[data-folder-path="Lab"]');
  const apps = dialog.locator('details[data-folder-path="Lab/Apps"]');
  const data = dialog.locator('details[data-folder-path="Lab/Data"]');
  await dialog.screenshot({ path: 'D:/AutoOps/frontend/dist/machine-import-collapsed.png' });
  await lab.locator(':scope > summary').focus();
  await page.keyboard.press('Enter');
  await apps.locator(':scope > summary').click();
  await data.locator(':scope > summary').click();
  await dialog.locator('details[data-folder-path=""] > summary').click();
  assert.equal(await dialog.getByRole('checkbox', { name: 'Windows host', exact: true }).isDisabled(), true);
  assert.equal(await dialog.getByRole('checkbox', { name: 'Existing host', exact: true }).isDisabled(), true);
  await dialog.getByRole('checkbox', { name: 'Select folder Lab/Data', exact: true }).uncheck();
  await dialog.getByRole('checkbox', { name: 'Add credential', exact: true }).check();
  assert.equal(await dialog.getByRole('textbox', { name: 'SSH username', exact: true }).inputValue(), 'ops');
  await dialog.getByRole('textbox', { name: 'SSH password', exact: true }).fill('discard-this-draft');
  await dialog.getByRole('checkbox', { name: 'Select folder Lab/Apps', exact: true }).uncheck();
  await dialog.getByRole('checkbox', { name: 'Select folder Lab/Apps', exact: true }).check();
  assert.equal(await dialog.getByRole('checkbox', { name: 'Add credential', exact: true }).isChecked(), false);
  await dialog.getByRole('checkbox', { name: 'Add credential', exact: true }).check();
  assert.equal(await dialog.getByRole('textbox', { name: 'SSH password', exact: true }).inputValue(), '', 'folder deselection discards credential drafts');
  // Required fields inside closed folders must become visible before native validation focuses them.
  await apps.locator(':scope > summary').click();
  await lab.locator(':scope > summary').click();
  await dialog.getByRole('button', { name: 'Import 1 machine', exact: true }).click();
  assert.equal(state.payload, undefined, 'native validation blocks empty password');
  assert.equal(await lab.getAttribute('open'), '');
  assert.equal(await apps.getAttribute('open'), '');
  await dialog.getByRole('textbox', { name: 'SSH password', exact: true }).fill('browser-fixture-secret');
  await dialog.getByRole('button', { name: 'Show SSH password', exact: true }).click();
  assert.equal(await dialog.getByRole('textbox', { name: 'SSH password', exact: true }).getAttribute('type'), 'text');
  await dialog.getByRole('button', { name: 'Hide SSH password', exact: true }).click();
  await dialog.screenshot({ path: 'D:/AutoOps/frontend/dist/machine-import-preview.png' });
  await dialog.getByRole('button', { name: 'Import 1 machine', exact: true }).click();
  await page.getByText('1 imported · 3 skipped · 0 failed', { exact: true }).waitFor();
  assert.match(state.payload, /"index":0/);
  assert.match(state.payload, /"username":"ops"/);
  assert.match(state.payload, /"password":"browser-fixture-secret"/);
  assert.doesNotMatch(state.payload, /"index":1/);
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await verifyFolderBrowser(page);

  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: /Language: עברית/ }).click();
  assert.equal(await page.locator('html').getAttribute('dir'), 'rtl');
  await page.locator('.fab').click();
  await page.getByRole('menuitem', { name: 'ייבוא חיבורי MobaXterm', exact: true }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'mobile.mxtsessions', mimeType: 'text/plain', buffer: Buffer.from('[Bookmarks]\nSubRep=Lab') });
  await page.getByText('נבחרו 2 מתוך 4 חיבורים', { exact: true }).waitFor();
  assert.equal(await page.getByRole('dialog').locator('details[open]').count(), 0, 'new file resets collapsed folders');
  const mobileFolder = page.getByRole('checkbox', { name: 'בחירת תיקייה Lab', exact: true });
  await mobileFolder.uncheck();
  await page.getByText('נבחרו 0 מתוך 4 חיבורים', { exact: true }).waitFor();
  await mobileFolder.check();
  assert.equal(await page.getByRole('dialog').locator('details[open]').count(), 0);
  await page.locator('details[data-folder-path="Lab"] > summary').click();
  await page.locator('details[data-folder-path="Lab/Apps"] > summary').click();
  await page.getByRole('checkbox', { name: 'הוספת פרטי גישה', exact: true }).check();
  const mobileOverflow = await page.locator('.modalBody').evaluate(el => el.scrollWidth > el.clientWidth);
  assert.equal(mobileOverflow, false, 'nested preview and credential fields fit a mobile viewport');
  await page.getByRole('dialog').screenshot({ path: 'D:/AutoOps/frontend/dist/machine-import-mobile.png' });
  const overflow = await page.getByRole('dialog').evaluate(el => el.scrollWidth > el.clientWidth);
  assert.equal(overflow, false, 'preview fits a mobile viewport');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(await page.locator('.fab').evaluate(el => document.activeElement === el), true, 'closing restores focus to the plus menu');
  assert.deepEqual(errors, []);
  console.log('PASS: collapsed/nested preview folders, selection, hidden-field validation, import/results, folder cards, breadcrumbs, Back/Forward, empty folders, search, Hebrew RTL mobile, focus');
} catch (error) {
  console.error(await page.locator('body').ariaSnapshot());
  throw error;
} finally {
  await browser.close();
}
